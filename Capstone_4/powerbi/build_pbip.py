def uid(*parts: str) -> str:
    return str(uuid.uuid5(NS, "/".join(parts)))


def q(name: str) -> str:
    """Quote a TMDL object name."""
    return "'" + name.replace("'", "''") + "'"


def classify(col: str, s: pd.Series) -> tuple[str, str]:
    """Return (TMDL dataType, Power Query type expression)."""
    if col in TEXT_IDS or s.isna().all():  # ids, and columns with no data yet, stay text
        return "string", "type text"
    if col.endswith("_date"):
        return "dateTime", "type date"
    if col.endswith("_ts") or col.endswith("_utc"):
        return "dateTime", "datetime"
    if pd.api.types.is_bool_dtype(s):
        return "boolean", "type logical"
    if col in MONEY_COLS:
        return "decimal", "Currency.Type"
    if pd.api.types.is_integer_dtype(s):
        return "int64", "Int64.Type"
    if pd.api.types.is_float_dtype(s):
        return "double", "type number"
    return "string", "type text"


def table_tmdl(name: str, csv: Path) -> tuple[str, list[str]]:
    df = pd.read_csv(csv)
    cols = list(df.columns)
    kinds = {c: classify(c, df[c]) for c in cols}
    add_sort = name == "fact_pipeline_aging"
    if add_sort:
        kinds["sort"] = ("int64", "Int64.Type")
        cols.append("sort")

    typed = [c for c in cols if not (add_sort and c == "sort") and kinds[c][1] != "datetime"]
    dts = [c for c in cols if kinds[c][1] == "datetime"]

    m = [
        "let",
        f'    Source = Csv.Document(File.Contents(CsvFolder & "\\{name}.csv"), '
        '[Delimiter = ",", Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),',
        "    Promoted = Table.PromoteHeaders(Source, [PromoteAllScalars = true]),",
    ]
    pairs = ", ".join(f'{{"{c}", {kinds[c][1]}}}' for c in typed)
    m.append(
        f'    Typed = Table.TransformColumnTypes(Promoted, {{{pairs}}}, "en-US"){"," if (dts or add_sort) else ""}'
    )
    last = "Typed"
    for i, c in enumerate(dts):
        step = f"Dt{i}"
        more = "," if (i < len(dts) - 1 or add_sort) else ""
        m.append(
            f'    {step} = Table.TransformColumns({last}, {{{{"{c}", each try DateTimeZone.RemoveZone('
            f"DateTimeZone.FromText(_)) otherwise null, type nullable datetime}}}}){more}"
        )
        last = step
    if add_sort:
        m.append(f'    Indexed = Table.AddIndexColumn({last}, "sort", 1, 1, Int64.Type)')
        last = "Indexed"
    m.append(f"in\n    {last}")

    out = [
        f"table {q(name) if re.search(r'[^A-Za-z0-9_]', name) else name}",
        f"\tlineageTag: {uid(name)}",
        "",
    ]
    # measures are inserted by the caller (they need the whole table list); marker line:
    out.append("%%MEASURES%%")
    for c in cols:
        dtype, _ = kinds[c]
        out.append(f"\tcolumn {q(c)}")
        out.append(f"\t\tdataType: {dtype}")
        if c in HIDDEN_COLS:
            out.append("\t\tisHidden")
        if dtype == "dateTime":
            out.append(
                "\t\tformatString: " + ("yyyy-mm-dd hh:nn:ss" if kinds[c][1] == "datetime" else "yyyy-mm-dd")
            )
        elif dtype == "decimal":
            out.append("\t\tformatString: \\$#,0.00")
        elif c in YEAR_LIKE:
            out.append("\t\tformatString: 0")
        out.append(f"\t\tlineageTag: {uid(name, c)}")
        out.append("\t\tsummarizeBy: none")
        out.append(f"\t\tsourceColumn: {c}")
        sb = SORT_BY.get((name, c))
        if sb:
            out.append(f"\t\tsortByColumn: {q(sb)}")
        out.append("")
    out.append(f"\tpartition {q(name + '-csv')} = m")
    out.append("\t\tmode: import")
    out.append("\t\tsource =")
    out.extend("\t\t\t" + line for line in "\n".join(m).splitlines())
    out.append("")
    return "\n".join(out), cols


def parse_measures(md: Path) -> list[tuple[str, str, str]]:
    """Return [(home_table, name, dax)] from measures.dax.md, in file order."""
    text = md.read_text(encoding="utf-8")
    result: list[tuple[str, str, str]] = []
    heading = ""
    for chunk in re.split(r"(?m)^(?=## )", text):
        head = chunk.splitlines()[0] if chunk.startswith("## ") else ""
        heading = head or heading
        home = next((t for key, t in HOME_BY_HEADING if key.lower() in heading.lower()), None)
        for block in re.findall(r"```dax\n(.*?)```", chunk, flags=re.S):
            for item in re.split(r"\n\s*\n(?=[A-Za-z][A-Za-z0-9 ]* =)", block.strip()):
                m = re.match(r"([A-Za-z][A-Za-z0-9 ]*?) =\s*(.*)", item.strip(), flags=re.S)
                if not m or home is None:
                    continue
                result.append((home, m.group(1).strip(), m.group(2).strip()))
    return result


def measure_tmdl(name: str, dax: str) -> str:
    lines = dax.splitlines()
    out = [f"\tmeasure {q(name)} ="]
    for ln in lines:
        out.append("\t\t\t" + ln.rstrip())
    if name in MONEY_MEASURES:
        out.append("\t\tformatString: \\$#,0")
    elif name in PERCENT_MEASURES:
        out.append("\t\tformatString: 0.0%")
    elif name in COUNT_MEASURES:
        out.append("\t\tformatString: #,0")
    out.append(f"\t\tlineageTag: {uid('measure', name)}")
    out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------- report builders


def lit(value) -> dict:
    if isinstance(value, bool):
        v = "true" if value else "false"
    elif isinstance(value, (int, float)):
        v = f"{value}D" if isinstance(value, float) else f"{value}L"
    else:
        v = "'" + str(value).replace("'", "''") + "'"
    return {"expr": {"Literal": {"Value": v}}}


def col(table: str, prop: str) -> dict:
    return {"Column": {"Expression": {"SourceRef": {"Entity": table}}, "Property": prop}}


def meas(table: str, prop: str) -> dict:
    return {"Measure": {"Expression": {"SourceRef": {"Entity": table}}, "Property": prop}}


def proj(field: dict, active: bool | None = None) -> dict:
    kind = "Measure" if "Measure" in field else "Column"
    e = field[kind]
    entity, prop = e["Expression"]["SourceRef"]["Entity"], e["Property"]
    p = {"field": field, "queryRef": f"{entity}.{prop}", "nativeQueryRef": prop}
    if active is not None:
        p["active"] = active
    return p


class Page:
    def __init__(self, key: str, title: str):
        self.key, self.title, self.visuals = key, title, []

    def add(
        self,
        vtype: str,
        x,
        y,
        w,
        h,
        roles: dict | None = None,
        title: str | None = None,
        objects: dict | None = None,
        filters: list | None = None,
        name: str | None = None,
    ):
        n = len(self.visuals) + 1
        v: dict = {"visualType": vtype}
        if roles:
            v["query"] = {
                "queryState": {r: {"projections": [proj(f) for f in fields]} for r, fields in roles.items()}
            }
        if objects:
            v["objects"] = objects
        if title:
            v["visualContainerObjects"] = {"title": [{"properties": {"show": lit(True), "text": lit(title)}}]}
        v["drillFilterOtherVisuals"] = True
        doc = {
            "$schema": S_VISUAL,
            "name": name or f"{self.key}_v{n:02d}",
            "position": {"x": x, "y": y, "z": n * 1000, "height": h, "width": w, "tabOrder": n * 1000},
            "visual": v,
        }
        if filters:
            doc["filterConfig"] = {"filters": filters}
        self.visuals.append(doc)


def in_filter(name: str, table: str, prop: str, values: list[str], negate: bool = False) -> dict:
    cond = {
        "In": {
            "Expressions": [{"Column": {"Expression": {"SourceRef": {"Source": "t"}}, "Property": prop}}],
            "Values": [[{"Literal": {"Value": "'" + v.replace("'", "''") + "'"}}] for v in values],
        }
    }
    if negate:
        cond = {"Not": {"Expression": cond}}
    return {
        "name": name,
        "field": col(table, prop),
        "type": "Categorical",
        "filter": {
            "Version": 2,
            "From": [{"Name": "t", "Entity": table, "Type": 0}],
            "Where": [{"Condition": cond}],
        },
    }


def textbox(text: str) -> dict:
    return {"general": [{"properties": {"paragraphs": [{"textRuns": [{"value": text}]}]}}]}


