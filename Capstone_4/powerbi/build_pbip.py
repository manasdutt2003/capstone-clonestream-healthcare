# --------------------------------------------------------------------------- writers


def write_json(path: Path, doc: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def build(csv_dir: Path, measures_md: Path, theme: Path, out: Path, with_theme: bool) -> dict:
    csvs = sorted(p for p in csv_dir.glob("*.csv") if p.stem != "manifest")
    if not csvs:
        sys.exit(f"No CSV files in {csv_dir}. Run: python -m hcls all")
    names = [p.stem for p in csvs]
    missing = {
        t
        for t in (
            "fact_metrics",
            "fact_scorecard",
            "fact_timeline",
            "fact_claims",
            "dim_bucket",
            "dim_severity",
            "fact_waterfall",
            "fact_link_health",
        )
        if t not in names
    }
    if missing:
        sys.exit(f"Missing expected tables: {sorted(missing)}")

    if out.exists():
        shutil.rmtree(out)
    sm = out / f"{PROJECT}.SemanticModel"
    rp = out / f"{PROJECT}.Report"

    # ---- project + semantic model
    write_json(
        out / f"{PROJECT}.pbip",
        {
            "version": "1.0",
            "artifacts": [{"report": {"path": f"{PROJECT}.Report"}}],
            "settings": {"enableAutoRecovery": True},
        },
    )
    write_text(out / ".gitignore", "**/.pbi/localSettings.json\n**/.pbi/cache.abf\n")
    write_json(sm / "definition.pbism", {"$schema": S_PBISM, "version": "4.0", "settings": {}})
    write_text(sm / "definition" / "database.tmdl", f"database {PROJECT}\n\tcompatibilityLevel: 1567\n")

    csv_abs = str(csv_dir.resolve()).replace("/", "\\") if sys.platform != "win32" else str(csv_dir.resolve())
    write_text(
        sm / "definition" / "expressions.tmdl",
        f'expression CsvFolder = "{csv_abs}" meta [IsParameterQuery=true, Type="Text", '
        "IsParameterQueryRequired=true]\n\tlineageTag: " + uid("expr", "CsvFolder") + "\n",
    )

    measures = parse_measures(measures_md) + [(t, n, d) for t, n, d in EXTRA_MEASURES]
    known = {n for _, n, _ in measures}
    by_table: dict[str, list[str]] = {}
    for home, name, dax in measures:
        by_table.setdefault(home, []).append(measure_tmdl(name, dax))

    columns: dict[str, list[str]] = {}
    for csv in csvs:
        text, cols = table_tmdl(csv.stem, csv)
        columns[csv.stem] = cols
        text = text.replace("%%MEASURES%%\n", "".join(m + "\n" for m in by_table.get(csv.stem, [])))
        write_text(sm / "definition" / "tables" / f"{csv.stem}.tmdl", text)

    for t, c1, t2, c2 in RELATIONSHIPS:
        assert c1 in columns[t] and c2 in columns[t2], (t, c1, t2, c2)

    rel = "\n".join(
        f"relationship {uid('rel', t, c1, t2, c2)}\n\tfromColumn: {t}.{q(c1)}\n\ttoColumn: {t2}.{q(c2)}\n"
        for t, c1, t2, c2 in RELATIONSHIPS
    )
    write_text(sm / "definition" / "relationships.tmdl", rel)

    model = [
        "model Model",
        "\tculture: en-US",
        "\tdefaultPowerBIDataSourceVersion: powerBI_V3",
        "\tdiscourageImplicitMeasures",
        "",
    ]
    model += [f"ref table {n}" for n in names] + ["", "ref expression CsvFolder", ""]
    write_text(sm / "definition" / "model.tmdl", "\n".join(model))

    # ---- report
    write_json(
        rp / "definition.pbir",
        {
            "$schema": S_PBIR,
            "version": "4.0",
            "datasetReference": {"byPath": {"path": f"../{PROJECT}.SemanticModel"}},
        },
    )
    write_json(rp / "definition" / "version.json", {"$schema": S_VERSION, "version": "2.0.0"})
    report = {"$schema": S_REPORT, "themeCollection": {}}
    if with_theme:
        report["themeCollection"]["customTheme"] = {
            "name": THEME_FILE,
            "reportVersionAtImport": {"visual": "2.0.0", "report": "3.0.0", "page": "2.0.0"},
            "type": "RegisteredResources",
        }
        report["resourcePackages"] = [
            {
                "name": "RegisteredResources",
                "type": "RegisteredResources",
                "items": [{"name": THEME_FILE, "path": THEME_FILE, "type": "CustomTheme"}],
            }
        ]
        dest = rp / "StaticResources" / "RegisteredResources" / THEME_FILE
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(theme, dest)
    write_json(rp / "definition" / "report.json", report)

    pages = build_pages()
    write_json(
        rp / "definition" / "pages" / "pages.json",
        {"$schema": S_PAGES, "pageOrder": [p.key for p in pages], "activePageName": pages[0].key},
    )
    n_vis = 0
    for p in pages:
        write_json(
            rp / "definition" / "pages" / p.key / "page.json",
            {
                "$schema": S_PAGE,
                "name": p.key,
                "displayName": p.title,
                "displayOption": "FitToPage",
                "height": CANVAS_H,
                "width": CANVAS_W,
            },
        )
        for v in p.visuals:
            write_json(rp / "definition" / "pages" / p.key / "visuals" / v["name"] / "visual.json", v)
            n_vis += 1

    # ---- consistency: every measure a visual uses must exist
    used = {
        q_["Measure"]["Property"]
        for p in pages
        for v in p.visuals
        for r in v["visual"].get("query", {}).get("queryState", {}).values()
        for q_ in [pr["field"] for pr in r["projections"]]
        if "Measure" in q_
    }
    unknown = used - known
    if unknown:
        sys.exit(f"Visuals use measures that are not defined: {sorted(unknown)}")
    return {"tables": len(names), "measures": len(measures), "pages": len(pages), "visuals": n_vis}


def validate(out: Path, schemas: Path) -> int:
    """Validate every generated JSON file against microsoft/json-schemas (local clone)."""
    from jsonschema import Draft7Validator
    from referencing import Registry, Resource

    base = "https://developer.microsoft.com/json-schemas/fabric/item/"
    root = schemas / "fabric" / "item"
    resources = []
    for f in root.rglob("*.json"):
        try:
            doc = json.loads(f.read_text(encoding="utf-8"))
        except ValueError:
            continue
        rid = doc.get("$id") if isinstance(doc, dict) else None
        url = rid or base + f.relative_to(root).as_posix()
        resources.append(
            (
                url,
                Resource.from_contents(
                    doc,
                    default_specification=__import__("referencing.jsonschema", fromlist=["DRAFT7"]).DRAFT7,
                ),
            )
        )
        resources.append((base + f.relative_to(root).as_posix(), resources[-1][1]))
    registry = Registry().with_resources(resources)
    bad = 0
    checked = 0
    for f in out.rglob("*.json"):
        doc = json.loads(f.read_text(encoding="utf-8"))
        sch = doc.get("$schema") if isinstance(doc, dict) else None
        if not sch or not sch.startswith(base):
            continue
        schema = {"$ref": sch}
        errs = list(Draft7Validator(schema, registry=registry).iter_errors(doc))
        checked += 1
        for e in errs[:5]:
            bad += 1
            print(f"SCHEMA ERROR {f.relative_to(out)}: {'/'.join(map(str, e.path))}: {e.message[:200]}")
    print(f"schema-validated {checked} files, {bad} errors")
    return bad


