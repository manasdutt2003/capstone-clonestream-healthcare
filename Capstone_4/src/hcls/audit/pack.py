"""The audit pack (Phase 5, task 5.4): scope, cause, money, fix and prevention in one document, with an evidence index.

Generated from the gold files by `facts.collect`, so each claim in it can be re-created with the command in the last table.
"""

from __future__ import annotations

import pandas as pd

from hcls.audit.facts import usd
from hcls.remediation import plan
from hcls.reports import md_table


def _tl(f: dict, rule: str) -> str:
    r = f["timeline"].loc[rule]
    return f"{rule} fails on {r['overall_rate_pct']:.1f}% of records overall, same rate every year (p = {r['p_value']:.2f}, {r['verdict']})"


def render(f: dict, audit: pd.DataFrame, metrics: pd.DataFrame) -> str:
    r, b, ev, bf = f["rule"], f["bucket"], f["expected"], f["backfill"]
    lh = f["link_health"]
    cl = lh.loc["Insurance_Claims -> Billing"]
    top = f["top"].copy()
    top["rows_failed"] = top["rows_failed"].astype(int)
    top["pct"] = top["pct_failed"].map(lambda x: f"{x:.1f}%")
    hyp = f["hypotheses"][["issue", "id", "hypothesis", "verdict"]]
    last = audit.iloc[-1] if len(audit) else None
    runs = len(audit)
    lines = [
        "# Audit pack",
        "",
        f"*As of {f['as_of']} | run {f['run_ts']} | commit {f['git_sha']}. Generated by `python -m hcls docs`; every number is read from `outputs/gold/`.*",
        "",
        "## 1. Summary for the auditor",
        "",
        f"- **Scope:** {f['rules_run']} rules run across {f['tables_total']} tables. {f['findings']} report findings; {f['critical_high']} are Critical or High ({f['severity'].get('Critical', 0)} Critical).",
        f"- **The three confirmed problems are real:** {r['C01']['rows']} of {r['C01']['of']} claims have no approved amount, {r['C02']['rows']} of {r['C02']['of']} visits have no appointment, {r['C03']['rows']} of {r['C03']['of']} medical records have no medication.",
        "- **Cause:** a design gap at the source, not a recent incident. The failure rate is flat across every year; nothing validates data on the way in.",
        f"- **Money:** {usd(b['Paid']['amount'])} is certain. {usd(b['Pipeline']['amount'])} is still being decided (expected {usd(ev['expected'], True)}). The groups tie to {usd(f['submitted_total'])} to the cent.",
        f"- **Fix:** at the source, with human review. A simulated backfill recovered {int(bf.loc['C03', 'applied_to_copy'])} of {int(bf.loc['C03', 'records_failing_before'])} and {int(bf.loc['C02', 'applied_to_copy'])} of {int(bf.loc['C02', 'records_failing_before'])}.",
        f"- **Prevention:** {f['validators']} ingest checks, a daily scorecard with alerts, and an audit log of every run.",
        "",
        "## 2. Answers to the eight key questions",
        "",
        "| # | Question | Answer | Evidence |",
        "|---|---|---|---|",
        f"| 1 | Where did it break? | C01: nowhere, it is by design (blank until the insurer decides). C02 and C03: the source application does not require an appointment or a medication entry. Cross-table links: the ETL key mapping, plus no foreign-key enforcement. {len(f['hypotheses'])} hypotheses tested; verdicts {', '.join(f'{v} {k.lower()}' for k, v in f['verdicts'].items())}. | `docs/02_root_cause_report.md` |",
        f"| 2 | When did it start? | No evidence of a start date. {_tl(f, 'C01')}; {_tl(f, 'C02')}. C03 cannot be dated (most records are from 2024 on). It has been like this from the start. | `rootcause/timeline_summary.csv` |",
        f"| 3 | How many more issues? | {f['findings']} findings in total, so {f['findings'] - 3} beyond the three confirmed. By severity (all {f['findings']}): {f['severity'].get('Critical', 0)} Critical, {f['severity'].get('High', 0)} High, {f['severity'].get('Medium', 0)} Medium, {f['severity'].get('Low', 0)} Low. | `docs/01_dq_scorecard.md` |",
        f"| 4 | Is it systemic? | Yes. Critical or High problems appear in {f['tables_with_critical_high']} of {f['tables_total']} tables, from independent causes with one thing in common: no validation at load. {f['links'].get('broken', 0)} of {f['links_total']} links between tables are broken and {f['links'].get('degraded', 0)} degraded. | `rootcause/lineage.csv` |",
        f"| 5 | Can we fix it? | Not by backfill. On a copy, {int(bf.loc['C03', 'applied_to_copy'])} of {int(bf.loc['C03', 'records_failing_before'])} medical records and {int(bf.loc['C02', 'applied_to_copy'])} of {int(bf.loc['C02', 'records_failing_before'])} visits could be filled safely. Fix at the source and review the rest by hand. C01 resolves when the insurer decides. | `docs/04_remediation_plan.md` |",
        f"| 6 | Should we refund? | Not determinable yet. The claim-to-bill link matches the right patient on {cl['same_patient']:.0f} of {cl['linked_rows']:.0f} claims. Hold refunds, fix the link, re-run. | `docs/03_finance_brief.md` |",
        f"| 7 | How confident are we? | Certain: paid {usd(b['Paid']['amount'])}, adjustment {usd(b['Adjustment']['amount'])}, denied {usd(b['Denied']['amount'])}. Estimated: pipeline {usd(b['Pipeline']['amount'])} (expected {usd(ev['expected'], True)}, range {usd(ev['low'], True)} to {usd(ev['high'], True)}; ceiling {usd(ev['ceiling_no_denials'], True)}), appeals {usd(b['Under appeal']['amount'])}. Held: {b['DQ Hold']['claims']} claims. | `outputs/gold/recon_buckets.csv` |",
        f"| 8 | How do we prevent it? | {f['validators']} ingest validators (would have rejected {f['validator_rows']:,} records), database constraints, a daily scorecard job with alerts, an audit log of every run, and a data contract with the claims system. | `remediation/validators.py` |",
        "",
        "## 3. Scorecard: the ten biggest problems",
        "",
        md_table(top, ["rank", "rule_id", "table", "column", "severity", "rows_failed", "pct"]),
        f"All {f['findings']} findings are in `docs/01_dq_scorecard.md` and `outputs/gold/dq_scorecard.csv`.",
        "",
        "## 4. Root causes",
        "",
        md_table(hyp),
        "",
        "## 5. Money: what is certain and what is estimated",
        "",
        md_table(
            pd.DataFrame(
                [{"bucket": k, "claims": v["claims"], "amount": usd(v["amount"])} for k, v in b.items()]
            )
        ),
        f"Every submitted dollar ({usd(f['submitted_total'])}) is in exactly one place. The expected value of the pipeline uses only decided claims and a seeded 5,000-draw range; the older {usd(ev['ceiling_no_denials'], True)} figure is the ceiling (no denials).",
        "",
        "## 6. Remediation",
        "",
        md_table(
            pd.DataFrame(plan.MATRIX).assign(rules=lambda d: d["rules"].map(", ".join)),
            ["id", "title", "action", "owner", "effort", "risk"],
        ),
        "Detail, rollback steps and the sign-off checklist: `docs/04_remediation_plan.md`.",
        "",
        "## 7. Prevention and monitoring",
        "",
        f"- **Ingest validators:** {f['validators']} checks, {f['validators_firing']} firing on today's data. They start warn-only (D-029).",
        f"- **Alerts:** status **{f['alerts']['status']}**, {len(f['alerts']['alerts'])} open ({f['alerts']['counts']}). Thresholds: Critical rule above 5%, drift above 10%, recon above 300 s.",
        "- **Jobs (design):** `dq_daily` 02:00 UTC, `recon_weekly` Mondays 06:00 UTC, `audit_nightly` 03:00 UTC (`databricks/jobs/`). The pipeline itself ran on Databricks Free Edition as a notebook job (D-041); these JSON definitions were not deployed (D-001).",
        "- **Release control:** the `deploy.yml` workflow needs a named reviewer on the `production` environment before the simulated deploy runs.",
        "",
        "## 8. Audit trail",
        "",
        f"`outputs/gold/audit_log.csv` holds one row per pipeline command ({runs} so far in this folder). `outputs/gold/audit_outputs.csv` lists the SHA-256 of every output file; `python -m hcls.audit.verify` reports any file changed since the last audit run.",
        "",
        *(
            [
                f"Latest entry: job `{last['job']}`, commit `{last['git_sha']}`, status {last['status']}, {int(last['rules_run'])} rules run, {int(last['rules_failed'])} failing, outputs digest `{str(last['outputs_digest'])[:12]}...`.",
                "",
            ]
            if last is not None
            else []
        ),
        "## 9. Open questions for owners",
        "",
        "1. **Clinical owner:** does `None` in the medication field mean no medication or not recorded?",
        "2. **ETL owner:** how are patient, appointment, billing and prescription ids generated? Is there a key-mapping table?",
        "3. **ETL owner:** where do the placeholder patient ids come from?",
        "4. **Finance:** can the paid total be confirmed against the insurer remittance or bank? Are the old open claims still being worked?",
        "5. **Compliance:** why were bills raised for cancelled or no-show appointments?",
        "6. **Platform owner:** who are the production reviewers and the alert recipients?",
        "",
        "## 10. Evidence index: every claim and how to reproduce it",
        "",
        md_table(
            pd.DataFrame(
                [
                    (
                        "Scorecard and timeline",
                        "`outputs/gold/dq_scorecard.csv`, `dq_timeline.csv`",
                        "`python -m hcls dq`",
                    ),
                    (
                        "Cleaned dataset (no rows dropped)",
                        "`data/clean/HCLS_cleaned.xlsx`, `change_log.csv`",
                        "`python -m hcls clean`",
                    ),
                    ("Root causes", "`outputs/gold/rootcause/*.csv`", "`python -m hcls rootcause`"),
                    (
                        "Reconciliation",
                        "`outputs/finance/*.xlsx`, `recon_buckets.csv`",
                        "`python -m hcls recon`",
                    ),
                    (
                        "Backfill simulation",
                        "`backfill_summary.csv`, `backfill_c03.csv`, `backfill_c02.csv`",
                        "`python -m hcls backfill`",
                    ),
                    (
                        "Validators",
                        "`validator_catch.csv`, `validator_violations.csv`",
                        "`python -m hcls validate`",
                    ),
                    ("Alerts", "`outputs/alerts.json`", "`python -m hcls alerts`"),
                    (
                        "Audit trail",
                        "`audit_log.csv`, `audit_outputs.csv`, `audit_metrics.csv`",
                        "`python -m hcls audit`",
                    ),
                    ("Power BI tables", "`outputs/powerbi/*.csv`", "`python -m hcls powerbi`"),
                    ("Everything", "all of the above", "`python -m hcls all`"),
                ],
                columns=["Claim", "Where", "Reproduce"],
            )
        ),
    ]
    return "\n".join(lines) + "\n"
