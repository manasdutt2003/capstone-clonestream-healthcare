        "",
        md_table(ev["c03_by_chapter"], list(ev["c03_by_chapter"].columns)),
        "",
        f"Backfill from Prescriptions: {int(bf.patient_has_any_prescription)} of {int(bf.none_records)} patients have any prescription and {int(bf.same_patient_and_doctor)} match the same doctor, so **automatic backfill is not possible**; the remaining 37 need the clinician.",
