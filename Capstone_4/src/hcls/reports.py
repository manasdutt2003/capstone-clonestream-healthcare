"""Markdown report renderers for the committed docs (generated, never hand-edited numbers)."""

from __future__ import annotations

import pandas as pd

from hcls import config

PLAIN_INT_COLS = {"first_seen", "last_seen", "year", "rank"}


def md_table(df: pd.DataFrame, cols: list[str] | None = None, fmt: dict | None = None) -> str:
    cols = cols or list(df.columns)
    fmt = fmt or {}
    head = "| " + " | ".join(cols) + " |\n|" + "|".join("---" for _ in cols) + "|\n"
    rows = []
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if pd.isna(v):
                cells.append("")
            elif c in fmt:
                cells.append(fmt[c](v))
            elif c in PLAIN_INT_COLS and not isinstance(v, str):
                cells.append(str(int(v)))
            elif isinstance(v, float) and v.is_integer():
                cells.append(f"{int(v):,}")
            else:
                cells.append(str(v).replace("|", "\\|"))
        rows.append("| " + " | ".join(cells) + " |")
    return head + "\n".join(rows) + "\n"


CONFIRMED = {
    "C01": "Insurance_Claims.approved_amount",
    "C02": "Visits.appointment_id",
    "C03": "Medical_Records.prescribed_meds",
}


def render_scorecard_doc(
    sc: pd.DataFrame, tl: pd.DataFrame, ri: pd.DataFrame, effect: pd.DataFrame, tsum: pd.DataFrame
) -> str:
    failing = sc[(sc["rows_failed"] > 0) & (sc["severity"] != "Info")]
    n_rules, n_fail = len(sc), len(failing)
    sev_counts = (
        failing.groupby("severity")
        .size()
        .reindex(["Critical", "High", "Medium", "Low"])
        .fillna(0)
        .astype(int)
    )
    n_info = int(((sc["rows_failed"] > 0) & (sc["severity"] == "Info")).sum())
    out = [
        "# Data Quality Scorecard",
        "",
        f"*Generated by `python -m hcls docs` from run `{sc['run_ts'].iloc[0]}` (commit `{sc['git_sha'].iloc[0]}`). "
        f"As-of date {config.as_of_date().isoformat()}. Do not edit by hand.*",
        "",
        "## Headline",
        "",
        f"- **{n_rules} rules** were run across the 19 data tables (every column, every foreign key, every date, plus {int((sc['source'] == 'registry').sum())} business rules).",
        f"- **{n_fail} rules found problems**: {sev_counts['Critical']} Critical, {sev_counts['High']} High, {sev_counts['Medium']} Medium, {sev_counts['Low']} Low "
        f"(plus {n_info} 'Info' items: fields that are empty by design, such as `denial_reason` on claims that were not denied).",
        "",
        "## The three confirmed issues from the brief",
        "",
    ]
    conf = sc[sc["rule_id"].isin(CONFIRMED)].copy()
    conf["issue"] = conf["rule_id"].map(CONFIRMED)
    out.append(
        md_table(
            conf, ["rule_id", "issue", "rows_failed", "rows_checked", "pct_failed", "first_seen", "last_seen"]
        )
    )
    out += [
        "",
        "`first_seen` / `last_seen` are the first and last year in which the problem occurs. The same problem appearing in "
        "every year points to a design gap, not a recent break (see the root-cause report).",
        "",
        "## Top 25 problems by impact",
        "",
        "Impact = severity weight x % of rows failing x stakeholder weight (weights in `config.yaml`).",
        "",
        md_table(
            failing.head(25),
            [
                "rank",
                "rule_id",
                "table",
                "name",
                "severity",
                "stakeholder",
                "rows_failed",
                "rows_checked",
                "pct_failed",
            ],
        ),
        "",
        "## Problems by table",
        "",
        md_table(tsum, ["table", "rules_failing", "critical", "high", "total_failed_cells"]),
        "",
        "## All Critical and High findings",
        "",
        md_table(
            failing[failing["severity"].isin(["Critical", "High"])],
            [
                "rule_id",
                "table",
                "name",
                "severity",
                "rows_failed",
                "rows_checked",
                "pct_failed",
                "impact_statement",
            ],
        ),
        "",
        "## Cross-check against the workbook's own `Referential_Integrity` sheet",
        "",
        "The workbook ships a sheet that lists foreign-key violations. We recomputed each line from the data.",
        "",
        md_table(
            ri,
            [
                "table",
                "fk_column",
                "references",
                "sheet_violation_types",
                "engine_violation_types",
                "engine_violating_rows",
                "verdict",
            ],
        ),
        "",
    ]
    bad = ri[ri["verdict"] != "matches"]
    if len(bad):
        out += [
            f"**{len(bad)} line(s) in the sheet do not match the data.** Where the sheet over-reports, the sheet compared text "
            "values (for example `'379'`) with numeric ids (`379`), so valid links were counted as violations. "
            "The scorecard uses the recomputed numbers (DECISIONS D-010).",
            "",
        ]
    fmt_effect = effect[
        effect["check_type"].isin(["validity", "timeliness"]) & (effect["rows_failed_raw"] > 0)
    ]
    fixed_rules = fmt_effect[fmt_effect["fixed"] > 0]
    out += [
        "## What cleaning fixed (raw vs cleaned data)",
        "",
        "The same rules were re-run on the cleaned data. Rules that now pass were fixed by standardisation; "
        "everything still failing needs a business or source-system fix and was deliberately **not** altered.",
        "",
        f"- Format / validity rules fully fixed: **{int((fixed_rules['rows_failed_clean'] == 0).sum())}** of {len(fixed_rules)} that had failures.",
        f"- Total failing cells before cleaning: **{int(effect['rows_failed_raw'].sum()):,}**; after: **{int(effect['rows_failed_clean'].sum()):,}**.",
        "",
        md_table(
            fixed_rules.sort_values("fixed", ascending=False).head(30),
            ["rule_id", "table", "column", "rows_failed_raw", "rows_failed_clean", "fixed"],
        ),
        "",
        "## Timeline",
        "",
        "Year-by-year failure rates for every rule are in `outputs/gold/dq_timeline.csv`. For the three confirmed issues:",
        "",
    ]
    t3 = (
        tl[tl["rule_id"].isin(CONFIRMED)]
        .pivot_table(index="year", columns="rule_id", values="pct_failed", aggfunc="first")
        .reset_index()
    )
    out.append(md_table(t3.round(1), list(t3.columns)))
    out.append("\n*(% of that year's rows failing the rule.)*\n")
    return "\n".join(out)


def render_cleaning_doc(
    summary: pd.DataFrame, changes: pd.DataFrame, raw_rows: dict[str, int], clean_rows: dict[str, int]
) -> str:
    total = len(changes)
    by_rule = summary.groupby("rule")["cells_changed"].sum().sort_values(ascending=False).reset_index()
    out = [
        "# Data Cleaning Report",
        "",
        f"*Generated from `outputs/gold/change_log.csv`. {total:,} cells changed across {summary['table'].nunique()} tables. "
        "No rows were added or removed.*",
        "",
        "## Principles",
        "",
        "1. **Never drop a row.** Row counts before and after are identical (table below).",
        "2. **Fix format, not facts.** Dates, phone numbers, spelling variants and placeholder text are standardised.",
        "3. **Null what is impossible, never invent.** A height of -10 cm, a birth date in the future or `not-an-email` becomes blank. "
        "The only computed value is BMI, which is a formula of height and weight.",
        "4. **Do not touch money, doses or foreign keys.** They are flagged by the DQ engine because changing them would hide the evidence auditors need.",
        "5. **Every change is logged** (table, Excel row, column, old value, new value, rule) in `change_log.csv`.",
        "",
        "## Date rules",
        "",
        "| Input | Becomes | Rule |",
        "|---|---|---|",
        "| `2024-03-12T09:00:00` in a date column | `2024-03-12` | `date_trimmed_time` |",
        "| `01/15/1987`, `01-01-2020` | `1987-01-15`, `2020-01-01` | `date_reformatted` (US month-first; a first number above 12 is treated as the day) |",
        "| `not available`, `tomorrow` | blank | `date_unparseable` |",
        "| `2025-13-01` (month 13) | blank | `date_invalid` (cannot tell whether day and month were swapped) |",
        "| `1800-01-01`, `1900-01-01`, `2099-01-01` | blank | `date_sentinel` (placeholder for 'no date') |",
        "| Date of birth after the as-of date | blank | `dob_in_future` |",
        "",
        "## Changes by rule",
        "",
        md_table(by_rule, ["rule", "cells_changed"]),
        "",
        "## Changes by table and column",
        "",
        md_table(summary, ["table", "column", "rule", "cells_changed"]),
        "",
        "## Row counts (nothing dropped)",
        "",
        "| Table | Raw rows | Clean rows |",
        "|---|---:|---:|",
    ]
    for t in raw_rows:
        out.append(f"| {t} | {raw_rows[t]:,} | {clean_rows.get(t, 0):,} |")
    out += [
        "",
        "## Deliberately not changed (flagged instead)",
        "",
        "- Orphan and sentinel foreign keys (for example patient ids 0, -1, 88888, 99991). Rules `R-*`.",
        "- Duplicate patient ids and e-mails (A16, A17). Merging people needs a business decision.",
        "- Money fields: negative or inconsistent claim and bill amounts (A07, A09, A10, A11, A44).",
        "- Drug doses and clinical vitals outside typical ranges (rules `X-*`). They may be genuine.",
        "- Date-order violations (A04, A05, A24, A25, A28, A32, A37). The correct order is unknown.",
        "- Future-dated events (rules `T-*`). We flag, we do not guess the true date.",
        "- Repeated 'default' dates such as 2020-01-01 or 2025-01-01 (rules `P-*`).",
        "",
        "## Judgement calls",
        "",
        "- **`None` means different things.** In `Medical_Records.prescribed_meds` the text `None` is treated as *missing* (this is the brief's 40-record defect). "
        "In allergy, surgery, family-history, alcohol, complications and accreditation columns `None` is a valid answer and is kept as `None`.",
        "- **Ambiguous values are blanked, not guessed:** blood type `AB` (no Rh sign), ethnicity `Human`, language `Spanglish`.",
        "- **Mapped with a stated assumption:** `2 beers/week` and `Sometimes` -> `Occasional`; `Smoker` -> `Current Smoker`; `caucasian` -> `White`; "
        "hospital city abbreviations (Philly, Jax, Indy, SF, OKC, DC, Vegas) -> full names.",
        "- **Placeholders:** the group number `G1234` (96 rows) and policy `POL-ABC` (59) are constants, not real identifiers, so they are blanked.",
    ]
    return "\n".join(out) + "\n"


