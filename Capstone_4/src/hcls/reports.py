        f"| 4 | Is it systemic? | **Yes.** Five of the six tested links match the same patient in under 5% of rows, and placeholder ids appear in {sent.table_name.nunique()} tables. One cause (no validation at entry) explains most of it; the key-mapping failure is a second, independent cause. |",
        "",
        "## 3. When did it start? (timeline test)",
        "",
        "Chi-square test that every year has the same failure rate. A p-value of 0.05 or more means no evidence of a change.",
        "",
        md_table(
            ev["timeline_summary"],
            [
                "rule_id",
                "table",
                "records",
                "failed",
                "overall_rate_pct",
                "years_with_failures",
                "first_year",
                "last_year",
                "years_tested",
                "p_value",
                "verdict",
            ],
        ),
        "",
        "Failure rate by year (%):",
        "",
        md_table(pivot, list(pivot.columns)),
